"""Summarize Locust runs of the /v1/search load test (loadtests/run.py).

For each user count: requests per second, p50/p95/p99 latency (ms) and error rate, read
from the "Aggregated" row of Locust's ``*_stats.csv``. Written to
``artifacts/load_results.{json,md}``.
"""

import csv
import json
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from causetrace.evaluation.retrieval_eval import git_sha

DEFAULT_JSON = Path("artifacts/load_results.json")
DEFAULT_MD = Path("artifacts/load_results.md")


def read_locust_stats(path: Path, users: int) -> dict[str, Any]:
    """One user level from a Locust stats CSV (its "Aggregated" row)."""
    with path.open(newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    agg = next(r for r in rows if r["Name"] == "Aggregated")
    requests = int(agg["Request Count"])
    failures = int(agg["Failure Count"])
    return {
        "users": users,
        "requests": requests,
        "failures": failures,
        "rps": float(agg["Requests/s"]),
        "p50_ms": float(agg["50%"]),
        "p95_ms": float(agg["95%"]),
        "p99_ms": float(agg["99%"]),
        "error_rate": failures / requests if requests else 0.0,
    }


def render_markdown(report: dict[str, Any]) -> str:
    out = [
        "# Load test: POST /v1/search",
        "",
        "Generated by `make loadtest` (loadtests/run.py); do not edit by hand.",
        "",
        f"- Git SHA: `{report['git_sha']}`",
        f"- Host: `{report['host']}`; {report['duration']} per level; run {report['run_at']}",
        "",
        "| Users | Requests | RPS | p50 ms | p95 ms | p99 ms | Error rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for lv in report["levels"]:
        out.append(
            f"| {lv['users']} | {lv['requests']} | {lv['rps']:.2f} | {lv['p50_ms']:.0f} "
            f"| {lv['p95_ms']:.0f} | {lv['p99_ms']:.0f} | {100 * lv['error_rate']:.2f}% |"
        )
    return "\n".join(out) + "\n"


def write_report(
    levels: Sequence[dict[str, Any]],
    *,
    host: str,
    duration: str,
    out_json: Path = DEFAULT_JSON,
    out_md: Path = DEFAULT_MD,
) -> dict[str, Any]:
    report = {
        "git_sha": git_sha(),
        "host": host,
        "duration": duration,
        "run_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "endpoint": "POST /v1/search",
        "levels": list(levels),
    }
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    out_md.write_text(render_markdown(report), encoding="utf-8")
    return report
